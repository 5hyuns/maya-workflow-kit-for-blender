"""Maya grey theme: apply / restore.

``maya.xml`` is generated by tools/make_theme.py (colour table with evidence
tags; ). Applying goes through Blender's theme preset
operator, which resets to the default theme first. The user's current theme
is saved to the extension's user folder before the first apply so it can be
restored. Never applied automatically.
"""

import os

import bpy

THEME_FILE = os.path.join(os.path.dirname(__file__), "maya.xml")
PRESET_MENU = "USERPREF_MT_interface_theme_presets"
_ADDON = __package__.rpartition(".")[0]


def backup_path(create=False):
    try:
        folder = bpy.utils.extension_path_user(_ADDON, create=create)
    except ValueError:  # legacy add-on build: no extension user folder
        folder = bpy.utils.user_resource('CONFIG', path="maya_kit", create=create)
    return os.path.join(folder, "theme_backup.xml")


def has_backup():
    return os.path.isfile(backup_path())


def save_backup():
    import rna_xml
    from bl_ui.space_userpref import USERPREF_MT_interface_theme_presets as presets
    path = backup_path(create=True)
    rna_xml.xml_file_write(bpy.context, path, presets.preset_xml_map)
    return path


def _execute(filepath):
    return bpy.ops.script.execute_preset(filepath=filepath, menu_idname=PRESET_MENU)


class MAYAKIT_OT_theme_apply(bpy.types.Operator):
    """Apply the Maya grey theme (your current theme is backed up first)"""
    bl_idname = "maya_kit.theme_apply"
    bl_label = "Apply Maya Theme"
    bl_options = {'REGISTER', 'INTERNAL'}

    def execute(self, context):
        if not has_backup():
            save_backup()
        _execute(THEME_FILE)
        self.report({'INFO'}, "Maya theme applied")
        return {'FINISHED'}


class MAYAKIT_OT_theme_restore(bpy.types.Operator):
    """Restore the theme you had before applying the Maya theme"""
    bl_idname = "maya_kit.theme_restore"
    bl_label = "Restore Previous Theme"
    bl_options = {'REGISTER', 'INTERNAL'}

    @classmethod
    def poll(cls, context):
        return has_backup()

    def execute(self, context):
        path = backup_path()
        _execute(path)
        os.remove(path)
        self.report({'INFO'}, "Previous theme restored")
        return {'FINISHED'}


classes = (MAYAKIT_OT_theme_apply, MAYAKIT_OT_theme_restore)

register, unregister = bpy.utils.register_classes_factory(classes)
