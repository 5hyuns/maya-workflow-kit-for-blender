"""Maya grey theme: apply / restore, driven by the ``maya_theme`` add-on option.

``maya.xml`` is generated by tools/make_theme.py (colour table with evidence
tags; , ). Applying goes through Blender's theme
preset operator, which resets to the default theme first. The user's current
theme is saved to the extension's user folder before the first apply and comes
back when the option is turned off or the add-on is disabled; enabling again
with the option on re-applies it (the prefs_preset pattern, ).
Not applied unless the user asks: the option, "Make Blender Maya" or the
welcome dialog.
"""

import os

import bpy

THEME_FILE = os.path.join(os.path.dirname(__file__), "maya.xml")
# The applied Maya theme is marked by the theme's name (saved with the preferences, not in the
# XML), not by ``filepath``: Blender's extension removal remembers ``themes[0].filepath`` and
# resets to the default theme when that file is gone afterwards, which would undo the restore
# the add-on's unregister just did ($S\addons_core\bl_pkg\bl_extension_ops.py:1233-1270, step 60).
THEME_NAME = "Maya"
_ADDON = __package__.rpartition(".")[0]


def backup_path(create=False):
    try:
        folder = bpy.utils.extension_path_user(_ADDON, create=create)
    except ValueError:  # legacy add-on build: no extension user folder
        folder = bpy.utils.user_resource('CONFIG', path="maya_kit", create=create)
    return os.path.join(folder, "theme_backup.xml")


def has_backup():
    return os.path.isfile(backup_path())


# Theme preset map relative to the Preferences struct (not bpy.context): the add-on also
# applies/restores from register()/unregister(), which Blender runs under a restricted context
# when it reloads the preferences (e.g. on switching to the MayaKit template, step 42), where
# context-based paths and operators fail. maya.xml and the backup are full theme dumps, so no
# reset to the default theme is needed first.
_MAP = (("themes[0]", "Theme"), ("ui_styles[0]", "ThemeStyle"))


def _prefs():
    return bpy.context.preferences


def _rna_xml():
    try:
        import rna_xml
    except ImportError:   # Blender 5.x renamed the module (step 53)
        import _rna_xml as rna_xml
    return rna_xml


def save_backup():
    rna_xml = _rna_xml()
    path = backup_path(create=True)
    rna_xml.xml_file_write(_prefs(), path, _MAP)
    # The theme's "filepath" (last preset loaded, shown in the theme UI) and name are not in the
    # XML: one line each.
    with open(path + ".filepath", "w", encoding="utf-8") as fh:
        fh.write(_prefs().themes[0].filepath + "\n" + _prefs().themes[0].name)
    return path


def _load(filepath):
    rna_xml = _rna_xml()
    from bl_ui.space_userpref import USERPREF_MT_interface_theme_presets as presets
    rna_xml.xml_file_run(_prefs(), filepath, _MAP, secure_types=presets.preset_xml_secure_types)


def apply():
    """Back up the user's theme (once) and apply the Maya theme. A backup next to a theme that is
    not the Maya one is stale (left by a disable; the user may have changed the theme since)."""
    if has_backup() and not is_applied():
        forget_backup()
    if not has_backup():
        save_backup()
    _load(THEME_FILE)
    _apply_moved(_prefs().themes[0])
    _prefs().themes[0].filepath = ""
    _prefs().themes[0].name = THEME_NAME
    _prefs().is_dirty = True


# maya.xml is written for Blender 4.5 (tools/make_theme.py); the XML loader skips attributes a later
# Blender doesn't have. Blender 5.x keeps some of them elsewhere: the animation
# editors' colours in theme.common.anim, region backgrounds in theme.regions. Those are copied from the
# same maya.xml values here (5.x path, 4.5 path in the XML).
_ANIM = ("preview_range", "channels", "channels_sub", "channel_group", "channel_group_active", "channel",
         "channel_selected", "keyframe", "keyframe_selected", "keyframe_extreme", "keyframe_extreme_selected",
         "keyframe_breakdown", "keyframe_breakdown_selected", "keyframe_jitter", "keyframe_jitter_selected",
         "keyframe_moving_hold", "keyframe_moving_hold_selected", "keyframe_generated",
         "keyframe_generated_selected", "long_key", "long_key_selected")
MOVED = (
    ("common.anim.playhead", "dopesheet_editor.frame_current"),
    *((f"common.anim.{n}", f"dopesheet_editor.{n}") for n in _ANIM),
    ("regions.sidebars.back", "view_3d.space.button"),
    ("regions.sidebars.tab_back", "view_3d.space.tab_back"),
    ("regions.channels.back", "dopesheet_editor.space_list.list"),
    ("regions.scrubbing.back", "dopesheet_editor.time_scrub_background"),
    ("regions.scrubbing.time_marker", "dopesheet_editor.time_marker_line"),
    ("regions.scrubbing.time_marker_selected", "dopesheet_editor.time_marker_line_selected"),
)


def _xml_value(root, path):
    """Hex colour of ``path`` (property elements, then the attribute) in a theme XML, or None."""
    *parts, attr = path.split(".")
    node = root
    for part in parts:
        prop = next((c for c in node.childNodes if c.nodeType == c.ELEMENT_NODE and c.tagName == part), None)
        if prop is None:
            return None
        node = next((c for c in prop.childNodes if c.nodeType == c.ELEMENT_NODE), None)
        if node is None:
            return None
    return node.getAttribute(attr) or None


def _resolve(theme, path):
    *parents, name = path.split(".")
    obj = theme
    for part in parents:
        obj = getattr(obj, part, None)
        if obj is None:
            return None, name
    return (obj if hasattr(obj, name) else None), name


def _apply_moved(theme):
    if not any(_resolve(theme, new)[0] is not None for new, _old in MOVED):
        return   # Blender 4.5: everything came from the XML
    import xml.dom.minidom
    root = xml.dom.minidom.parse(THEME_FILE).getElementsByTagName("Theme")[0]
    for new, old in MOVED:
        obj, name = _resolve(theme, new)
        value = _xml_value(root, old)
        if obj is None or not value:
            continue
        h = value.lstrip("#")
        rgb = [int(h[i:i + 2], 16) / 255 for i in (0, 2, 4)]
        current = getattr(obj, name)
        if len(current) == 4:
            rgb.append(int(h[6:8], 16) / 255 if len(h) >= 8 else current[3])
        setattr(obj, name, rgb)
    # widget colour sets a later Blender added (wcol_curve ...): square and flat like the rest (step 44)
    ui = theme.user_interface
    for prop in ui.bl_rna.properties:
        if prop.identifier.startswith("wcol_") and prop.identifier != "wcol_state":
            w = getattr(ui, prop.identifier)
            w.roundness = 0.0
            w.show_shaded = False


def is_applied():
    """The Maya theme is the current one (apply() names the theme ``THEME_NAME``; loading a theme
    preset or resetting to the default theme does not keep the name)."""
    return _prefs().themes[0].name == THEME_NAME


def restore(forget=True):
    """Put the backed-up theme back; ``forget`` deletes the backup. False if there was none.

    The add-on's unregister keeps the backup (``forget=False``): Blender also unregisters add-ons
    when it quits, after the preferences (with the Maya theme) were saved, and the next start
    must still find the user's theme."""
    path = backup_path()
    if not os.path.isfile(path):
        return False
    _load(path)
    filepath, name = "", "Default"
    if os.path.isfile(path + ".filepath"):
        with open(path + ".filepath", encoding="utf-8") as fh:
            filepath, _, name = fh.read().partition("\n")
    if forget:
        forget_backup()
    _prefs().themes[0].filepath = filepath
    _prefs().themes[0].name = name if name and name != THEME_NAME else "Default"
    _prefs().is_dirty = True
    return True


def forget_backup():
    path = backup_path()
    for leftover in (path, path + ".filepath"):
        if os.path.isfile(leftover):
            os.remove(leftover)


class MAYAKIT_OT_theme_apply(bpy.types.Operator):
    """Apply the Maya grey theme (your current theme is backed up first)"""
    bl_idname = "maya_kit.theme_apply"
    bl_label = "Apply Maya Theme"
    bl_options = {'REGISTER', 'INTERNAL'}

    def execute(self, context):
        from .. import preferences
        prefs = preferences.get(context)
        if prefs.maya_theme:
            apply()          # re-apply (e.g. after editing the theme by hand)
        else:
            prefs.maya_theme = True   # update callback applies
        self.report({'INFO'}, "Maya theme applied")
        return {'FINISHED'}


class MAYAKIT_OT_theme_restore(bpy.types.Operator):
    """Restore the theme you had before applying the Maya theme"""
    bl_idname = "maya_kit.theme_restore"
    bl_label = "Restore Previous Theme"
    bl_options = {'REGISTER', 'INTERNAL'}

    @classmethod
    def poll(cls, context):
        return has_backup()

    def execute(self, context):
        from .. import preferences
        prefs = preferences.get(context)
        if prefs.maya_theme:
            prefs.maya_theme = False  # update callback restores
        else:
            restore()
        self.report({'INFO'}, "Previous theme restored")
        return {'FINISHED'}


classes = (MAYAKIT_OT_theme_apply, MAYAKIT_OT_theme_restore)


def register():
    for cls in classes:
        bpy.utils.register_class(cls)
    from .. import preferences
    # Option on from an earlier session but restored on disable (or by a preferences reload,
    # which unregisters and registers again): apply again. After Blender quit in Maya mode the
    # Maya theme was saved and the backup holds the user's theme: apply() keeps it.
    if preferences.get().maya_theme:
        apply()


def unregister():
    # Disabling the add-on gives the user's theme back (the option stays on for the next enable).
    restore(forget=False)
    for cls in reversed(classes):
        bpy.utils.unregister_class(cls)
