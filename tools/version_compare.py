"""The same look_compare scenes on Blender 4.5 and each 5.x, side by side (step 119).

    python tools/version_compare.py      # after tools/look_compare.py ran with ALLSET_LOOK_TAG=4.5 / <5.x version>

Reads tmp/look_env_<tag>/shots/*.png (written by tools/look_shots.py), and for every 5.x tag writes into
research/maya/screens/version_compare/<tag>/:
  - <shot>.png: 4.5 | 5.x | difference map (black = same, red = CIEDE2000 > 5, yellow = 2-5);
  - table.md: per shot, mean ΔE00 and the share of pixels with ΔE00 > 5 against 4.5.
Runs itself in `blender -b` (images via bpy, numpy maths).
"""

import os
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "research" / "maya" / "screens" / "version_compare"


def lab(img):
    """sRGB image (h, w, 3) in 0..1 -> CIELAB (D65)."""
    import numpy as np
    c = np.where(img <= 0.04045, img / 12.92, ((img + 0.055) / 1.055) ** 2.4)
    m = np.array([[0.4124, 0.3576, 0.1805], [0.2126, 0.7152, 0.0722], [0.0193, 0.1192, 0.9505]])
    xyz = c @ m.T / np.array([0.95047, 1.0, 1.08883])
    f = np.where(xyz > 216 / 24389, np.cbrt(xyz), (24389 / 27 * xyz + 16) / 116)
    return np.stack([116 * f[..., 1] - 16, 500 * (f[..., 0] - f[..., 1]), 200 * (f[..., 1] - f[..., 2])], -1)


def de2000(lab1, lab2):
    """Vectorised CIEDE2000 (Sharma, Wu, Dalal 2005), same formula as look_compare.de2000_lab."""
    import numpy as np
    L1, a1, b1 = lab1[..., 0], lab1[..., 1], lab1[..., 2]
    L2, a2, b2 = lab2[..., 0], lab2[..., 1], lab2[..., 2]
    C1, C2 = np.hypot(a1, b1), np.hypot(a2, b2)
    Cm = (C1 + C2) / 2
    G = 0.5 * (1 - np.sqrt(Cm ** 7 / (Cm ** 7 + 25 ** 7)))
    a1p, a2p = (1 + G) * a1, (1 + G) * a2
    C1p, C2p = np.hypot(a1p, b1), np.hypot(a2p, b2)
    h1p = np.degrees(np.arctan2(b1, a1p)) % 360
    h2p = np.degrees(np.arctan2(b2, a2p)) % 360
    dLp, dCp = L2 - L1, C2p - C1p
    d = h2p - h1p
    dh = np.where(C1p * C2p == 0, 0, np.where(np.abs(d) <= 180, d, np.where(h2p > h1p, d - 360, d + 360)))
    dHp = 2 * np.sqrt(C1p * C2p) * np.sin(np.radians(dh / 2))
    Lpm, Cpm = (L1 + L2) / 2, (C1p + C2p) / 2
    s = h1p + h2p
    hpm = np.where(C1p * C2p == 0, s, np.where(np.abs(h1p - h2p) <= 180, s / 2,
                                               np.where(s < 360, (s + 360) / 2, (s - 360) / 2)))
    T = (1 - 0.17 * np.cos(np.radians(hpm - 30)) + 0.24 * np.cos(np.radians(2 * hpm))
         + 0.32 * np.cos(np.radians(3 * hpm + 6)) - 0.20 * np.cos(np.radians(4 * hpm - 63)))
    dtheta = 30 * np.exp(-(((hpm - 275) / 25) ** 2))
    Rc = 2 * np.sqrt(Cpm ** 7 / (Cpm ** 7 + 25 ** 7))
    Sl = 1 + 0.015 * (Lpm - 50) ** 2 / np.sqrt(20 + (Lpm - 50) ** 2)
    Sc, Sh = 1 + 0.045 * Cpm, 1 + 0.015 * Cpm * T
    Rt = -np.sin(np.radians(2 * dtheta)) * Rc
    return np.sqrt((dLp / Sl) ** 2 + (dCp / Sc) ** 2 + (dHp / Sh) ** 2 + Rt * (dCp / Sc) * (dHp / Sh))


SHIFT = 3   # px: Blender 5.x keeps areas 2 px further from the window edge (step 53), so layouts move by a few px


def shift_tolerant(a, b):
    """Per pixel of ``a``, the smallest CIEDE2000 to ``b`` within +-SHIFT px: a colour change counts, a widget
    that moved by a few pixels doesn't. Only pixels still above 2 are tried at the next shift (speed)."""
    import numpy as np
    la, lb = lab(a.astype(np.float64)), lab(b.astype(np.float64))
    h, w = la.shape[:2]
    pad = np.pad(lb, ((SHIFT, SHIFT), (SHIFT, SHIFT), (0, 0)), mode="edge")
    best = de2000(la, lb)
    ys, xs = np.nonzero(best > 2)
    for dy in range(-SHIFT, SHIFT + 1):
        for dx in range(-SHIFT, SHIFT + 1):
            if (dy or dx) and len(ys):
                d = de2000(la[ys, xs], pad[ys + SHIFT + dy, xs + SHIFT + dx])
                best[ys, xs] = np.minimum(best[ys, xs], d)
                keep = best[ys, xs] > 2
                ys, xs = ys[keep], xs[keep]
    return best


def in_blender():
    import numpy as np
    sys.path.insert(0, str(ROOT / "tools"))
    import look_data as L
    from look_compare import save_png
    base = ROOT / "tmp" / "look_env_4.5" / "shots"
    tags = sorted(p.name[len("look_env_"):] for p in (ROOT / "tmp").glob("look_env_5.*"))
    for tag in tags:
        shots = ROOT / "tmp" / f"look_env_{tag}" / "shots"
        out = OUT / tag
        out.mkdir(parents=True, exist_ok=True)
        lines = [f"# Blender {tag} vs 4.5: the same look_compare scenes", "",
                 "Generated by `python tools/version_compare.py`. ΔE00 per pixel against the 4.5 shot "
                 "(same window size, same scene), the smallest within +-3 px (5.x areas sit 2 px further in, so widgets move a "
                 "little; a colour change still counts). Images: 4.5 | " + tag + " | difference (red > 5, yellow 2-5).", "",
                 "| shot | mean ΔE00 | pixels ΔE00 > 5 | pixels ΔE00 2-5 |", "|---|---|---|---|"]
        for a_path in sorted(base.glob("*.png")):
            b_path = shots / a_path.name
            if not b_path.exists():
                continue
            a, b = L.load_rgb(a_path), L.load_rgb(b_path)
            h, w = min(a.shape[0], b.shape[0]), min(a.shape[1], b.shape[1])
            a, b = a[:h, :w], b[:h, :w]
            de = shift_tolerant(a, b)
            far, near = float((de > 5).mean()), float(((de > 2) & (de <= 5)).mean())
            heat = np.zeros_like(a)
            heat[de > 5] = (1.0, 0.0, 0.0)
            heat[(de > 2) & (de <= 5)] = (1.0, 1.0, 0.0)
            gap = np.ones((h, 8, 3), np.float32)
            save_png(np.concatenate([a, gap, b, gap, heat], axis=1), out / a_path.name)
            lines.append(f"| {a_path.stem} | {de.mean():.2f} | {far * 100:.2f} % | {near * 100:.2f} % |")
        (out / "table.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
        print(f"version_compare: {tag}: {len(lines) - 6} shots -> {out.relative_to(ROOT)}")


def main():
    sys.path.insert(0, str(ROOT / "tools"))
    import build
    r = subprocess.run([os.environ.get("BLENDER", build.DEFAULT_BLENDER), "-b", "--factory-startup",
                        "--python-exit-code", "1", "--python", __file__], env=build.sandbox_env(),
                       stdin=subprocess.DEVNULL, capture_output=True, text=True, encoding="utf-8", errors="replace")
    for line in r.stdout.splitlines():
        if line.startswith("version_compare"):
            print(line)
    if r.returncode:
        sys.stderr.write(r.stdout[-3000:] + r.stderr[-3000:])
    return r.returncode


if __name__ == "__main__":
    try:
        import bpy  # noqa: F401
    except ImportError:
        sys.exit(main())
    in_blender()
