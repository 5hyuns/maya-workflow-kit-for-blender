"""Write tests/maya2026_rig_data.py: the Maya 2026 joint / rig measurements (step 242, Issue #159).

Sources (not tracked, see CLAUDE.md): research/maya/re/joint_rig_2026_<topic>.json for the six topics below and the
mayapy cross-check files (``*_<check>.json``) in the private folders $ALLSET_RIG_MEASURED_DIR / $ALLSET_RIG_MEASURED2_DIR.
Only numbers and attribute names are copied: command text and tracebacks that the capture scripts stored next to
the numbers are dropped (``DROP``), so the fixture holds measurements only.

    python tools/gen_maya2026_rig_data.py
"""
import json
import os
import pprint

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RE = os.path.join(ROOT, "research", "maya", "re")
MEASURED = os.environ.get("ALLSET_RIG_MEASURED_DIR", "")
OUT = os.path.join(ROOT, "tests", "maya2026_rig_data.py")

TOPICS = ("joint_math", "skeleton_menu", "ik", "skinning", "constraints_sdk", "select_pick")
# table name -> check name: the private file is <check>.json or *_<check>.json
MEASURED_FILES = {"MEASURED_IK_VERIFY": "ik_verify", "MEASURED_SC_VERIFY": "sc_verify",
                  "MEASURED_SC_VERIFY2": "sc_verify2", "MEASURED_DQ_SCALE": "dq_scale"}
# second measurement pass: orientJoint rule checks (step 244)
MEASURED2 = os.environ.get("ALLSET_RIG_MEASURED2_DIR", "")
MEASURED2_FILES = {"OJ_VERIFY": "oj_verify"}
# joint_rig_2026_joint_tool.json: only the measured GUI numbers (the file also holds recorded Tool Settings commands)
JOINT_TOOL_KEYS = ("jointCtx", "front_clicks", "front_chain", "jointDisplayScale")
# key paths whose values are recorded command text or a capture-script traceback, not measurements
DROP = {
    ("skeleton", "move_skinned_joints", "ERROR"),
    ("skeleton2", "move_skinned_joints", "moveJointsMode_mel_lines"),
    ("skeleton2", "move_skinned_joints", "moveJointsMode_calls"),
}


def _key(k):
    """A capture key named after a Maya menu routine -> a neutral key ("<command>_optionVars" -> "option_vars")."""
    if isinstance(k, str) and k.startswith("perform") and k.endswith("_optionVars"):
        return "option_vars"
    return k


def _clean(value, path=()):
    if isinstance(value, dict):
        out = {}
        for k, v in value.items():
            if path + (k,) in DROP:
                continue
            out[_key(k)] = _clean(v, path + (k,))
        return out
    if isinstance(value, list):
        return [_clean(v, path) for v in value]
    if isinstance(value, str) and ("$" in value or "`" in value or "Traceback" in value):
        raise SystemExit(f"script text at {'/'.join(map(str, path))}: add the path to DROP")
    return value


def _find(folder, check):
    names = sorted(n for n in os.listdir(folder) if n == f"{check}.json" or n.endswith(f"_{check}.json"))
    if len(names) != 1:
        raise SystemExit(f"{folder}: expected one {check}.json, found {names}")
    return os.path.join(folder, names[0])


def _load(path):
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def main():
    parts = [
        '"""Maya 2026 joint / rig measurements (mayapy + GUI Maya measurements, 2026-10-27) for the 0.6.0 rig\n'
        'upgrade (steps 242-252). Generated by tools/gen_maya2026_rig_data.py from research/maya/re/joint_rig_2026_*.json\n'
        '(rules in the .md next to each) and the measured cross-checks (private notes). Maya units,\n'
        'Maya Y-up world, row-vector matrices, degrees; positions under "w" / "world" are world space. Do not edit by hand.\n'
        'Builders and the Maya <-> Blender axis map: tests/maya2026_rig.py."""\n'
    ]
    for topic in TOPICS:
        data = _clean(_load(os.path.join(RE, f"joint_rig_2026_{topic}.json")))
        parts.append(f"\n# research/maya/re/joint_rig_2026_{topic}.json\n{topic.upper()} = "
                     + pprint.pformat(data, width=118, sort_dicts=False) + "\n")
    gui = _load(os.path.join(RE, "joint_rig_2026_joint_tool.json"))["gui"]
    data = _clean({k: gui[k] for k in JOINT_TOOL_KEYS})
    parts.append("\n# research/maya/re/joint_rig_2026_joint_tool.json gui (measured GUI Joint Tool, step 244)\n"
                 "JOINT_TOOL = " + pprint.pformat(data, width=118, sort_dicts=False) + "\n")
    checks = [(MEASURED, t, c) for t, c in MEASURED_FILES.items()] + [(MEASURED2, t, c) for t, c in MEASURED2_FILES.items()]
    for folder, table, check in checks:
        data = _clean(_load(_find(folder, check)))
        parts.append(f"\n# measured cross-check {check} (mayapy, private notes)\n"
                     f"{table} = " + pprint.pformat(data, width=118, sort_dicts=False) + "\n")
    names = [t.upper() for t in TOPICS] + ["JOINT_TOOL"] + [t for _f, t, _c in checks]
    parts.append("\nALL = {" + ", ".join(f'"{n}": {n}' for n in names) + "}\n")
    text = "".join(parts)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"wrote {OUT} ({len(text)} bytes, {len(names)} tables)")


if __name__ == "__main__":
    main()
