"""Generate src/maya_kit/ui/menu_hotkeys.py: the Maya hotkey shown right-aligned beside a kit menu item (step 108).

    python tools/gen_menu_hotkeys.py

Maya shows, beside a menu item, the hotkey bound to the runTimeCommand the item runs. Source:
research/maya/menus.json (item -> command, via tools/gen_menu_data.py so the label paths match ui/menu_data.py) and
research/maya/hotkeys_default.json (command -> key, global context, Windows / all platforms). A key is listed only when
the kit's Maya keyconfig really does the Maya thing with it (src/maya_kit/keymap/mapping.py status KIT or IC, checked
against the keyconfig by tools/gen_keymap_mapping.py), so a menu never advertises a key that does something else.
Only key names and label paths are written (no MEL; docs/user_decisions.md #6).
"""

import importlib.util
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MENUS = ROOT / "research" / "maya" / "menus.json"
HOTKEYS = ROOT / "research" / "maya" / "hotkeys_default.json"
OUT = ROOT / "src" / "maya_kit" / "ui" / "menu_hotkeys.py"

# Maya (Qt) key names in menus (research/maya/screens/audit7/maya/menu_Modeling_Edit_Mesh.png: "Ctrl+Del",
# "Ctrl+Alt+Left"); modifiers in Qt's order Ctrl, Alt, Shift ("Ctrl+Shift+S", "Ctrl+Alt+S").
KEY_NAMES = {"Delete": "Del", "Page_Up": "PgUp", "Page_Down": "PgDown", "Insert": "Ins", "Return": "Return",
             "Backspace": "Backspace", "Esc": "Esc", "Home": "Home", "Space": "Space", " ": "Space",
             "Up": "Up", "Down": "Down", "Left": "Left", "Right": "Right"}


def _load(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def maya_text(hotkey):
    """"Ctrl+Shift+S" for a hotkeys_default.json entry."""
    key, mods = hotkey["key"], hotkey["modifiers"]
    shift = "sht" in mods
    if len(key) == 1 and key.isalpha():
        shift = shift or key.isupper()
        name = key.upper()
    else:
        name = KEY_NAMES.get(key, key)
    parts = [m for m, flag in (("Ctrl", "ctl" in mods), ("Alt", "alt" in mods), ("Shift", shift)) if flag]
    return "+".join(parts + [name])


def _paths(items, prefix):
    seen = {}
    for it in items:
        if it[0] == "-":
            continue
        n = seen[it[0]] = seen.get(it[0], 0) + 1
        path = f"{prefix}/{it[0]}" + (f"#{n}" if n > 1 else "")
        yield path
        if len(it) > 1:
            yield from _paths(it[1], path)


def table():
    sys.path.insert(0, str(ROOT / "tools"))
    import gen_menu_data
    mapping = _load("mapping", ROOT / "src" / "maya_kit" / "keymap" / "mapping.py")
    data = json.loads(MENUS.read_text(encoding="utf-8"))
    menus = gen_menu_data.build(data)
    commands = {}
    for m in menus.values():
        for path, cmd in gen_menu_data.command_paths(m[3], m[0]):
            commands.setdefault(path, cmd)
        for path in _paths(m[3], m[0]):      # items without a command of their own still match by label
            commands.setdefault(path, "")
    # A menu item records the MEL it runs (menus.json "command"); a hotkey records its runTimeCommand's MEL
    # ("press.command"), label and menu category ("Menu items.Modeling.Edit Mesh"): match on the MEL, else on
    # (menu, label) for items whose MEL Maya builds at run time ("$cmd").
    by_mel, by_label = {}, {}
    for hk in json.loads(HOTKEYS.read_text(encoding="utf-8"))["hotkeys"]:
        if hk["platform"] == "mac-only" or hk.get("context", "global") != "global":
            continue
        entry = mapping.entry_for(hk)
        if entry is None or entry["status"] not in ("KIT", "IC"):
            continue
        press = hk.get("press") or {}
        text = maya_text(hk)
        cat, label = press.get("category", ""), press.get("label")
        for table_, key in ((by_mel, (press.get("command") or "").strip()),
                            (by_label, (cat.rsplit(".", 1)[-1], label) if cat.startswith("Menu items.") and label
                             else None)):
            # the first factory key wins, except that Maya's menus show Del rather than Backspace
            # (Delete Edge/Vertex: Ctrl+Del, audit7 menu_Modeling_Edit_Mesh.png)
            if key and (key not in table_ or "Backspace" in table_[key]):
                table_[key] = text
    out = {}
    for path, cmd in sorted(commands.items()):
        top, leaf = path.split("/", 1)[0], path.rsplit("/", 1)[-1].split("#")[0]
        key = by_mel.get(cmd.strip()) or by_label.get((top, leaf)) or by_label.get((top, leaf.rstrip(".")))
        if key:
            out[path] = key
    return out


def main():
    rows = table()
    lines = ['# SPDX-License-Identifier: GPL-3.0-or-later',
             '"""Maya hotkeys shown beside kit menu items (generated by tools/gen_menu_hotkeys.py — do not edit).',
             '',
             'Menu label path -> Maya key text, for items whose Maya command has a factory hotkey that the kit binds the',
             'Maya way (keymap/mapping.py KIT / IC). Sources: research/maya/menus.json, hotkeys_default.json."""',
             '',
             'HOTKEYS = {']
    lines += [f'    {p!r}: {k!r},' for p, k in rows.items()]
    lines.append('}')
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(rows)} items with a Maya hotkey")


if __name__ == "__main__":
    main()
