"""Generate src/allset/keymap/hotkey_data.py: Maya 2022's factory hotkey list for the kit Hotkey Editor (step 215).

    python tools/gen_hotkey_data.py

Source: research/maya/hotkeys_default.json (468 bindings of hotkeySetup.mel; research/ is not shipped). Only key
names, modifiers, hotkey contexts, runTimeCommand / nameCommand names, Hotkey Editor categories and the source line
are written — no MEL, no annotations (docs/user_decisions.md #6), like docs/keymap_mapping.md.
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
HOTKEYS = ROOT / "research" / "maya" / "hotkeys_default.json"
OUT = ROOT / "src" / "allset" / "keymap" / "hotkey_data.py"

sys.path.insert(0, str(ROOT / "tools"))
from gen_menu_hotkeys import maya_text  # noqa: E402  Qt key text ("Ctrl+Shift+S"), step 108


def _text(hk):
    text = maya_text(hk)
    return ("Cmd+" + text) if "cmd" in hk["modifiers"] else text


def rows():
    hotkeys = json.loads(HOTKEYS.read_text(encoding="utf-8"))["hotkeys"]
    out = []
    for hk in hotkeys:
        press = hk.get("press") or {}
        release = hk.get("release") or {}
        out.append((hk["key"], tuple(hk["modifiers"]), _text(hk), hk.get("context", "global"),
                    press.get("runTimeCommand") or "", press.get("nameCommand") or "",
                    release.get("runTimeCommand") or "", hk.get("category") or "", hk["line"], hk["platform"]))
    return out


def main():
    lines = ['# SPDX-License-Identifier: GPL-3.0-or-later',
             '"""Maya 2022 factory hotkeys for the kit Hotkey Editor (generated by tools/gen_hotkey_data.py — do not '
             'edit).',
             '',
             'One tuple per hotkeySetup.mel binding (research/maya/hotkeys_default.json): (key, modifiers, Maya key text,',
             'hotkey context, press runTimeCommand, press nameCommand, release runTimeCommand, Hotkey Editor category,',
             'hotkeySetup.mel line, platform). Names and keys only (docs/user_decisions.md #6)."""',
             '',
             'FIELDS = ("key", "modifiers", "text", "context", "command", "name_command", "release", "category", '
             '"line", "platform")',
             '',
             'HOTKEYS = (']
    for row in rows():
        lines.append(f"    {row!r},")
    lines.append(")")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(rows())} hotkeys)")


if __name__ == "__main__":
    main()
