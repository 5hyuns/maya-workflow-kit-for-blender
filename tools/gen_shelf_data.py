"""Generate src/allset/ui/shelf_data.py from research/maya/shelves.json.

    python tools/gen_shelf_data.py

Keeps the Maya factory shelf tabs in their default order with each button's label
and runTimeCommand name only — no MEL (docs/user_decisions.md #6): a command that
is not a bare identifier (a MEL expression with arguments) is stored as None and
mapped by label in ui/shelf_map.py. Plan: docs/steps/step_12.md 「계획」 2.
"""

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "research" / "maya" / "shelves.json"
OUT = ROOT / "src" / "allset" / "ui" / "shelf_data.py"

# Default tab order (research/maya/shelves.md:25-28, initShelf.mel:458-485) and tab labels
# (shelves.md:21-22, MayaStrings m_shelfLabel.*). "Custom" is the empty user shelf.
ORDER = (("CurvesSurfaces", "Curves / Surfaces"), ("Polygons", "Poly Modeling"),
         ("Sculpting", "Sculpting"), ("Rigging", "Rigging"), ("Animation", "Animation"),
         ("Rendering", "Rendering"), ("FX", "FX"), ("FXCaching", "FX Caching"))
DEFAULT = "Polygons"   # General.json selectedShelf (shelves.md:30-31)
_IDENT = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")


def main():
    data = json.loads(SRC.read_text(encoding="utf-8"))["factory"]
    shelves = []
    # Maya's shelf separators: the factory shelf files carry none, so they come from the Maya 2022 GUI grab of every
    # factory shelf (research/maya/screens/top113/_top113.json "shelves": icons and 12 px separator frames in x order,
    # step 113) — only for shelves whose live button count equals the file's.
    grab = ROOT / "research" / "maya" / "screens" / "top113" / "_top113.json"
    live = json.loads(grab.read_text(encoding="utf-8")).get("shelves", {}) if grab.exists() else {}
    gaps = {}
    for name, label in ORDER:
        buttons = []
        for b in data[name]:
            cmd = (b.get("command") or "").strip()
            buttons.append((b.get("label", ""), cmd if _IDENT.match(cmd) else None))
        shelves.append((name, label, buttons))
        seq = live.get(name, [])
        n, idx = 0, []
        for kind, _rect in seq:
            if kind == "sep":
                idx.append(n)
            else:
                n += 1
        if seq and n == len(buttons):
            gaps[name] = [i for i in idx if 0 < i < n]
    lines = ['# SPDX-License-Identifier: GPL-3.0-or-later',
             '"""Maya 2022 factory shelves (generated by tools/gen_shelf_data.py — do not edit).',
             '',
             'Source: research/maya/shelves.json (factory shelf files; labels and runTimeCommand',
             'names only). SHELVES = [(file name, tab label, [(button label, runTimeCommand | None)])].',
             'GAPS = {file name: button indices that follow a Maya shelf separator}.',
             '"""',
             '',
             f'DEFAULT = {DEFAULT!r}',
             '',
             'SHELVES = [']
    for name, label, buttons in shelves:
        lines.append(f'    ({name!r}, {label!r}, [')
        for b in buttons:
            lines.append(f'        {b!r},')
        lines.append('    ]),')
    lines.append(']')
    lines.append('')
    lines.append('GAPS = {')
    for name, idx in gaps.items():
        lines.append(f'    {name!r}: {tuple(sorted(set(idx)))!r},')
    lines.append('}')
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"gen_shelf_data: wrote {OUT.relative_to(ROOT)} "
          f"({len(shelves)} shelves, {sum(len(s[2]) for s in shelves)} buttons)")


if __name__ == "__main__":
    main()
