"""Generate src/allset/ui/shelf_data.py from research/maya/shelves.json.

    python tools/gen_shelf_data.py

Keeps the Maya 2026 factory shelf tabs in their default order with each button's label
and runTimeCommand name only — no MEL (docs/user_decisions.md #6): a command that
is not a bare identifier (a MEL expression with arguments) is stored as None and
mapped by label in ui/shelf_map.py. Plan: docs/steps/step_12.md 「계획」 2, step 269.
"""

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "research" / "maya" / "shelves.json"
OUT = ROOT / "src" / "allset" / "ui" / "shelf_data.py"

# Default tab order of a new Maya 2026 user (measured in Maya 2026: the default shelf list) with the tab labels.
# Tab labels = Maya 2026's shelf label strings (measured in Maya 2026: "Polygons" is "Poly Modeling", "UVEditing" is
# "UV Editing", "FXCaching" is "FX Caching"; the others are their file names). "Custom" is the empty user shelf.
ORDER = (("Curves", "Curves"), ("Surfaces", "Surfaces"), ("Polygons", "Poly Modeling"),
         ("Sculpting", "Sculpting"), ("UVEditing", "UV Editing"), ("Rigging", "Rigging"),
         ("Animation", "Animation"), ("Rendering", "Rendering"), ("FX", "FX"), ("FXCaching", "FX Caching"))
DEFAULT = "Polygons"   # the General workspace's selected shelf (research/maya/workspaces.json)
_IDENT = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")


def main():
    data = json.loads(SRC.read_text(encoding="utf-8"))["factory"]
    shelves = []
    # Maya's shelf separators (12 px) are in the factory shelf files themselves since Maya 2026; their positions
    # match the Maya 2022 GUI grab of every shelf that step 113 measured (Polygons, Sculpting, FX, FX Caching).
    gaps = {}
    for name, label in ORDER:
        buttons, idx = [], []
        for b in data[name]:
            if b.get("separator"):
                idx.append(len(buttons))
                continue
            cmd = (b.get("command") or "").strip()
            buttons.append((b.get("label", ""), cmd if _IDENT.match(cmd) else None))
        shelves.append((name, label, buttons))
        gaps[name] = [i for i in idx if 0 < i < len(buttons)]
    lines = ['# SPDX-License-Identifier: GPL-3.0-or-later',
             '"""Maya 2026 factory shelves (generated by tools/gen_shelf_data.py — do not edit).',
             '',
             'Source: research/maya/shelves.json (factory shelf files; labels and runTimeCommand',
             'names only). SHELVES = [(file name, tab label, [(button label, runTimeCommand | None)])].',
             'GAPS = {file name: button indices that follow a Maya shelf separator}.',
             '"""',
             '',
             f'DEFAULT = {DEFAULT!r}',
             '',
             'SHELVES = [']
    for name, label, buttons in shelves:
        lines.append(f'    ({name!r}, {label!r}, [')
        for b in buttons:
            lines.append(f'        {b!r},')
        lines.append('    ]),')
    lines.append(']')
    lines.append('')
    lines.append('GAPS = {')
    for name, idx in gaps.items():
        lines.append(f'    {name!r}: {tuple(sorted(set(idx)))!r},')
    lines.append('}')
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"gen_shelf_data: wrote {OUT.relative_to(ROOT)} "
          f"({len(shelves)} shelves, {sum(len(s[2]) for s in shelves)} buttons)")


if __name__ == "__main__":
    main()
